library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity rom is
    port(   clk      : in std_logic;
            endereco : in unsigned(6 downto 0);
            dado     : out unsigned(14 downto 0));
end entity;

architecture a_rom of rom is
    type mem is array (0 to 127) of unsigned(14 downto 0);
    constant conteudo_rom : mem := (
        0  => B"0001_000_00000001", -- LI R0, 1
        1  => B"0001_001_00000001", -- LI R1, 1
        2  => B"0001_010_00100000", -- LI R2, 32
        
        3  => B"0010_000_000_00000", -- LoopInit: MOV A, R0
        4  => B"1101_000_000_00000", -- SW (R0)
        5  => B"0100_000_001_00000", -- ADD A, R1
        6  => B"0011_000_000_00000", -- MOV R0, A
        7  => B"0111_000_010_00000", -- AND A, R2
        8  => B"1001_000_11111010", -- BLE -6

        9  => B"0001_000_00000010", -- LI R0, 2
        10 => B"0001_100_00000010", -- LI R4, 2
        11 => B"0001_101_00000000", -- LI R5, 0
        
        12 => B"0010_000_000_00000", -- Loop2: MOV A, R0
        13 => B"0100_000_100_00000", -- ADD A, R4
        14 => B"0011_000_000_00000", -- MOV R0, A
        15 => B"0111_000_010_00000", -- AND A, R2
        16 => B"1001_000_00000010", -- BLE +2
        17 => B"1111_0010110_0000", -- JMP 22 (Exit Bloco)
        
        18 => B"0000_000_000_00000", -- (placeholder)
        19 => B"0010_000_101_00000", -- MOV A, R5
        20 => B"1101_000_000_00000", -- SW (R0)
        21 => B"1111_0001100_0000", -- JMP 12 (Volta Loop2)
        
        22 => B"0001_000_00000011", -- LI R0, 3
        23 => B"0001_100_00000011", -- LI R4, 3
        
        24 => B"0010_000_000_00000", -- Loop3: MOV A, R0
        25 => B"0100_000_100_00000", -- ADD A, R4
        26 => B"0011_000_000_00000", -- MOV R0, A
        27 => B"0111_000_010_00000", -- AND A, R2
        28 => B"1001_000_00000010", -- BLE +2 (vai p/ 31)
        29 => B"1111_0100010_0000", -- JMP 34 (Exit Bloco)
        
        30 => B"0000_000_000_00000",
        31 => B"0010_000_101_00000", -- MOV A, R5
        32 => B"1101_000_000_00000", -- SW (R0)
        33 => B"1111_0011000_0000", -- JMP 24

        34 => B"0001_000_00000101", -- LI R0, 5
        35 => B"0001_100_00000101", -- LI R4, 5
        
        36 => B"0010_000_000_00000", -- Loop5: MOV A, R0
        37 => B"0100_000_100_00000", -- ADD A, R4
        38 => B"0011_000_000_00000", -- MOV R0, A
        39 => B"0111_000_010_00000", -- AND A, R2
        40 => B"1001_000_00000010", -- BLE +2 (vai p/ 43)
        41 => B"1111_0101110_0000", -- JMP 46 (Exit Bloco)
        
        42 => B"0000_000_000_00000",
        43 => B"0010_000_101_00000", -- MOV A, R5
        44 => B"1101_000_000_00000", -- SW (R0)
        45 => B"1111_0100100_0000", -- JMP 36
        
        46 => B"0001_000_00000010", -- LI R0, 2
        47 => B"0001_100_00000001", -- LI R4, 1
        
        48 => B"1100_000_000_00000", -- LoopRead: LW (R0) -> A
        49 => B"0011_001_000_00000", -- MOV R1, A
        50 => B"0010_000_000_00000", -- MOV A, R0
        51 => B"0100_000_100_00000", -- ADD A, R4
        52 => B"0011_000_000_00000", -- MOV R0, A
        53 => B"0111_000_010_00000", -- AND A, R2
        54 => B"1001_000_11111001", -- BLE -7 (vai p/ 48)

        55 => B"1110_000_000_00000", -- HALT
        
        others => B"0000_000_000_00000"  -- NOP
    );
begin 
    process(clk)
    begin
        if(rising_edge(clk)) then
            dado <= conteudo_rom(to_integer(endereco));
        end if;
    end process;
end architecture;
